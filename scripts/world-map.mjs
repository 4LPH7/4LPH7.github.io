// Builds src/data/worldMap.ts (dot grids for the location card) from Natural Earth land outlines.
// Usage: node scripts/world-map.mjs <path/to/land-50m.json>
// The input is world-atlas's land-50m.json (https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-50m.json, public domain).
import { readFileSync, writeFileSync } from "node:fs";

const topo = JSON.parse(readFileSync(process.argv[2], "utf8"));
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;

// Decode the quantised, delta-encoded arcs into [lon, lat] points.
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; });
});
const ring = (ids) => ids.flatMap((id, n) => {
  const pts = id < 0 ? [...arcs[~id]].reverse() : arcs[id];
  return n ? pts.slice(1) : pts;
});
const rings = topo.objects.land.geometries.flatMap((g) =>
  (g.type === "Polygon" ? [g.arcs] : g.arcs).flatMap((poly) => poly.map(ring)));

// Even-odd scanline fill: which cells on a row of latitude `lat` are land.
function row(lat, lon0, step, cols) {
  const xs = [];
  for (const r of rings)
    for (let i = 0; i < r.length - 1; i++) {
      const [x1, y1] = r[i];
      const [x2, y2] = r[i + 1];
      if ((y1 > lat) !== (y2 > lat)) xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
    }
  xs.sort((a, b) => a - b);
  const out = new Uint8Array(cols);
  for (let c = 0; c < cols; c++) {
    const lon = lon0 + (c + 0.5) * step;
    let inside = false;
    for (const x of xs) { if (x > lon) break; inside = !inside; }
    out[c] = inside ? 1 : 0;
  }
  return out;
}

// Rough Tamil Nadu outline (lon, lat): the coast is cut by the real land mask, so only the inland borders are approximate.
const TN = [[80.35, 13.6], [79.6, 13.25], [79.1, 12.95], [78.3, 12.85], [77.75, 12.75], [77.5, 12.2], [77.6, 11.8], [77.2, 11.55],
  [76.5, 11.6], [76.25, 11.2], [76.75, 10.8], [77.15, 10.2], [77.15, 9.5], [77.2, 8.9], [77.5, 8.0], [78.2, 8.6], [79.0, 9.1],
  [79.5, 9.3], [80.0, 10.3], [80.0, 11.2], [79.95, 12.0], [80.35, 12.8]];
const inTN = (lon, lat) => {
  let inside = false;
  for (let i = 0, j = TN.length - 1; i < TN.length; j = i++) {
    const [xi, yi] = TN[i];
    const [xj, yj] = TN[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};

// World: 1 degree, 84N to 58S. One bit per cell.
const W = { lon0: -180, lat0: 84, step: 1, cols: 360, rows: 142 };
const wbits = new Uint8Array(Math.ceil((W.cols * W.rows) / 8));
for (let r = 0; r < W.rows; r++) {
  const cells = row(W.lat0 - (r + 0.5) * W.step, W.lon0, W.step, W.cols);
  cells.forEach((v, c) => { if (v) { const k = r * W.cols + c; wbits[k >> 3] |= 0x80 >> (k & 7); } });
}

// South India: 0.25 degree, 68E-90E, 25N-3N. Two bits per cell: 0 sea, 1 land, 2 Tamil Nadu.
const S = { lon0: 68, lat0: 25, step: 0.25, cols: 88, rows: 88 };
const scells = new Uint8Array(Math.ceil((S.cols * S.rows) / 4));
for (let r = 0; r < S.rows; r++) {
  const lat = S.lat0 - (r + 0.5) * S.step;
  const cells = row(lat, S.lon0, S.step, S.cols);
  cells.forEach((v, c) => {
    const val = v ? (inTN(S.lon0 + (c + 0.5) * S.step, lat) ? 2 : 1) : 0;
    const k = r * S.cols + c;
    scells[k >> 2] |= val << (6 - (k & 3) * 2);
  });
}

const b64 = (u8) => Buffer.from(u8).toString("base64");
writeFileSync(new URL("../src/data/worldMap.ts", import.meta.url), `// Generated by scripts/world-map.mjs from Natural Earth land (world-atlas land-50m, public domain). Do not edit by hand.

/** Land mask, 1 bit per 1-degree cell, row-major from (lon0, lat0) going east then south. */
export const WORLD = { lon0: ${W.lon0}, lat0: ${W.lat0}, step: ${W.step}, cols: ${W.cols}, rows: ${W.rows}, data: "${b64(wbits)}" };

/** South India at 0.25 degrees, 2 bits per cell: 0 sea, 1 land, 2 Tamil Nadu (approximate inland borders). */
export const SOUTH_INDIA = { lon0: ${S.lon0}, lat0: ${S.lat0}, step: ${S.step}, cols: ${S.cols}, rows: ${S.rows}, data: "${b64(scells)}" };
`);
console.log("world bytes", wbits.length, "south bytes", scells.length);
